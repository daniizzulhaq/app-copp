<?php

use App\Http\Controllers\ActivityController;
use App\Http\Controllers\AnalysisReportController;
use App\Http\Controllers\AuthController;
use App\Http\Controllers\DashboardController;
use App\Http\Controllers\DailyRoiClaimController;
use App\Http\Controllers\ManualDepositController;
use App\Http\Controllers\MemberController;
use App\Http\Controllers\OperationsController;
use App\Http\Controllers\PackageController;
use App\Http\Controllers\PaymentController;
use App\Http\Controllers\PortfolioController;
use App\Http\Controllers\ProfileController;
use App\Http\Controllers\ReportController;
use App\Http\Controllers\ScenarioController;
use App\Http\Controllers\WalletController;
use App\Http\Controllers\WithdrawalController;
use Illuminate\Support\Facades\Route;

Route::view('/', 'landing')->name('home');
Route::middleware('guest')->group(function () {
    Route::view('/login', 'auth.login')->name('login');
    Route::post('/login', [AuthController::class, 'login'])->middleware('throttle:20,1');
    Route::view('/register', 'auth.register')->name('register');
    Route::post('/register', [AuthController::class, 'register'])->middleware('throttle:5,1');
    Route::view('/forgot-password', 'auth.forgot')->name('password.request');
    Route::post('/forgot-password', [AuthController::class, 'forgot'])->middleware('throttle:3,1')->name('password.email');
    Route::get('/reset-password/{token}', fn (string $token) => view('auth.reset', compact('token')))->name('password.reset');
    Route::post('/reset-password', [AuthController::class, 'reset'])->middleware('throttle:5,1')->name('password.update');
});
Route::post('/sandbox/webhook', [PaymentController::class, 'webhook'])->middleware('throttle:120,1')->name('sandbox.webhook');
Route::middleware(['auth', 'active'])->group(function () {
    Route::post('/logout', [AuthController::class, 'logout'])->name('logout');
    Route::view('/verify-email', 'auth.verify')->name('verification.notice');
    Route::get('/verify-email/{id}/{hash}', [AuthController::class, 'verify'])->middleware(['signed', 'throttle:6,1'])->name('verification.verify');
    Route::post('/email/verification-notification', [AuthController::class, 'resend'])->middleware('throttle:3,1')->name('verification.send');
    Route::get('/profile', [ProfileController::class, 'index'])->name('profile');
    Route::patch('/profile', [ProfileController::class, 'update']);
    Route::put('/profile/bank-account', [ProfileController::class, 'bankAccount'])->middleware('throttle:20,1')->name('profile.bank-account');
    Route::put('/profile/password', [ProfileController::class, 'password'])->middleware('throttle:5,1');
    Route::delete('/profile/sessions', [ProfileController::class, 'revoke']);
    Route::post('/profile/2fa/setup', [ProfileController::class, 'setupTwoFactor'])->middleware('throttle:5,1');
    Route::post('/profile/2fa/confirm', [ProfileController::class, 'confirmTwoFactor'])->middleware('throttle:5,1');
    Route::delete('/profile/2fa', [ProfileController::class, 'disableTwoFactor'])->middleware('throttle:5,1');
    Route::middleware('verified')->group(function () {
        Route::get('/dashboard', DashboardController::class)->name('dashboard');
        Route::get('/wallet', WalletController::class)->name('wallet')->middleware('can:transact');
        Route::get('/payments', [PaymentController::class, 'index'])->name('payments.index');
        Route::post('/payments', [PaymentController::class, 'store']);
        Route::get('/payments/{invoice}', [PaymentController::class, 'show'])->name('payments.show');
        Route::post('/payments/{invoice}/simulate', [PaymentController::class, 'simulate'])->middleware('throttle:20,1');
        Route::post('/payments/{invoice}/submit', [ManualDepositController::class, 'submit'])->middleware('throttle:20,1');
        Route::get('/payments/{invoice}/proof', [ManualDepositController::class, 'proof'])->name('payments.proof');
        Route::post('/payments/{invoice}/cancel', [ManualDepositController::class, 'cancel'])->middleware('throttle:20,1');
        Route::patch('/payments/{invoice}/review', [ManualDepositController::class, 'review'])->middleware('can:manage');
        Route::get('/operations', [OperationsController::class, 'index'])->name('operations')->middleware('can:view-reports');
        Route::post('/operations/roi', [OperationsController::class, 'process'])->middleware('can:manage');
        Route::get('/investments', [PortfolioController::class, 'index'])->name('investments.index');
        Route::post('/roi/{obligation}/claim', DailyRoiClaimController::class)->middleware(['can:transact', 'throttle:30,1'])->name('roi.claim');
        Route::post('/investments', [PortfolioController::class, 'store']);
        Route::get('/investments/{investment}', [PortfolioController::class, 'show'])->name('investments.show');
        Route::get('/withdrawals', [WithdrawalController::class, 'index'])->name('withdrawals.index');
        Route::post('/withdrawals', [WithdrawalController::class, 'store']);
        Route::patch('/withdrawals/{withdrawal}', [WithdrawalController::class, 'review'])->middleware('can:manage');
        Route::get('/packages', [PackageController::class, 'index'])->name('packages.index');
        Route::middleware('can:manage')->group(function () {
            Route::get('/packages/create', [PackageController::class, 'create']);
            Route::post('/packages', [PackageController::class, 'store']);
            Route::get('/packages/{package}/edit', [PackageController::class, 'edit']);
            Route::put('/packages/{package}', [PackageController::class, 'update']);
            Route::delete('/packages/{package}', [PackageController::class, 'archive']);
            Route::get('/members/create', [MemberController::class, 'create']);
            Route::post('/members', [MemberController::class, 'store']);
            Route::get('/members/{member}/edit', [MemberController::class, 'edit']);
            Route::put('/members/{member}', [MemberController::class, 'update']);
            Route::delete('/members/{member}', [MemberController::class, 'destroy']);
            Route::get('/scenarios/create', [ScenarioController::class, 'create']);
            Route::post('/scenarios', [ScenarioController::class, 'store']);
            Route::get('/scenarios/{scenario}/edit', [ScenarioController::class, 'edit']);
            Route::put('/scenarios/{scenario}', [ScenarioController::class, 'update']);
            Route::post('/scenarios/{scenario}/run', [ScenarioController::class, 'run']);
            Route::post('/scenarios/{scenario}/reset', [ScenarioController::class, 'reset']);
            Route::delete('/scenarios/{scenario}', [ScenarioController::class, 'archive']);
            Route::post('/transactions/{transaction}/reverse', [ReportController::class, 'reverse']);
            Route::get('/settings', [ReportController::class, 'settings'])->name('settings');
            Route::put('/settings', [ReportController::class, 'saveSettings']);
        });
        Route::middleware('can:view-reports')->group(function () {
            Route::get('/analysis-reports', AnalysisReportController::class)->name('analysis-reports');
            Route::get('/members', [MemberController::class, 'index'])->name('members.index');
            Route::get('/members/{member}', [MemberController::class, 'show']);
            Route::get('/scenarios', [ScenarioController::class, 'index'])->name('scenarios.index');
            Route::get('/scenarios/{scenario}', [ScenarioController::class, 'show']);
            Route::get('/reports', [ReportController::class, 'index'])->name('reports.index');
            Route::get('/ledger', [ReportController::class, 'ledger'])->name('ledger');
            Route::get('/transactions/{transaction}', [ReportController::class, 'transaction']);
            Route::get('/audit', [ReportController::class, 'audit'])->name('audit');
        });
        Route::get('/referrals', [ActivityController::class, 'referrals'])->name('referrals');
        Route::get('/notifications', [ActivityController::class, 'notifications'])->name('notifications');
        Route::post('/notifications/read-all', [ActivityController::class, 'readAll']);
        Route::patch('/notifications/{notification}', [ActivityController::class, 'read']);
        Route::get('/activity', [ActivityController::class, 'activity'])->name('activity');
    });
});
